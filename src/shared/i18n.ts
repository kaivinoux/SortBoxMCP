export const MESSAGES: Record<AppLanguage, TranslationBundle> = {
  en: EN_MESSAGES,
  fr: FR_MESSAGES,
  es: ES_MESSAGES,
  pt: PT_MESSAGES,
  it: IT_MESSAGES,
  de: DE_MESSAGES,
};

export function normalizeLanguage(raw?: string | null): AppLanguage {
  const clean = (raw ?? "").trim().toLowerCase().slice(0, 2);
  if (
    clean === "en" ||
    clean === "fr" ||
    clean === "es" ||
    clean === "pt" ||
    clean === "it" ||
    clean === "de"
  ) {
    return clean;
  }
  return DEFAULT_LANGUAGE;
}

export function getMessages(lang: AppLanguage = DEFAULT_LANGUAGE): TranslationBundle {
  return MESSAGES[lang] ?? EN_MESSAGES;
}

export function getLocaleForLanguage(lang: AppLanguage = DEFAULT_LANGUAGE): string {
  return SUPPORTED_LANGUAGES.find((l) => l.code === lang)?.locale ?? "en-US";
}

export function formatMessage(
  template: string,
  vars: Record<string, string | number>,
): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_m, k) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
  );
}

export function formatBytesLocalized(
  bytes: number,
  lang: AppLanguage = DEFAULT_LANGUAGE,
): string {
  const t = getMessages(lang).triage;
  if (bytes < 1024) return `${bytes} ${t.bytesB}`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} ${t.bytesKB}`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} ${t.bytesMB}`;
}

export function localizeCategory(
  category: string | null | undefined,
  lang: AppLanguage = DEFAULT_LANGUAGE,
): string | null {
  if (!category) return null;
  const map = getMessages(lang).categories;
  return map[category] ?? category;
}
